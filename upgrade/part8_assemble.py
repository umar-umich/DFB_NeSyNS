#!/usr/bin/env python3
"""Part 8: assemble the final report from whatever evidence exists, and apply every pre-set rule.

    <discern_ext python> upgrade/part8_assemble.py

The brief requires seven items by the end, "whatever the individual experiments show", and requires
that unrun cells read TODO(run) rather than being filled in. So this reads the evidence files on
disk, applies each pre-set rule to what is actually there, and writes the report with the gaps
marked. Running it early is useful rather than premature: it shows exactly which cells are still
missing and never invents one.

Every rule below is the brief's, quoted in the row it decides, and each verdict carries the number
that produced it so a reader can check the arithmetic rather than trust the word.
"""
from __future__ import annotations

import json, sys
from pathlib import Path

import numpy as np

ROOT = Path("/data/umar/Repos/DFB_NeSyNS")
A = ROOT / "analysis/upgrade"
TODO = "TODO(run)"


def j(path):
    p = A / path
    return json.load(open(p)) if p.exists() else None


def fmt(x, n=4):
    return TODO if x is None else (f"{x:.{n}f}" if isinstance(x, (int, float)) else str(x))


def screen_table():
    rows = []
    for name in ("clip", "dinov3", "pe", "pe_spatial", "pe_core_l",
                 "clipL", "clipN", "pe_core_lL", "pe_core_lN"):
        d = j(f"screen_{name}.json")
        if not d:
            rows.append((name, None, None, None, None, None)); continue
        s, m = d["standalone_mean"], d["fused_mean"]
        rows.append((name, s["dev_v31"], s["ffpp_val_auroc"], m["auroc"], m["fpr_real"], m["loo"]["APP"]))
    return rows


def readout_table():
    rows = []
    for bb in ("pe_core_l", "clip"):
        for ro in ("last", "mid", "half", "lastmid", "lastmidhalf"):
            d = j(f"screen_{bb}-{ro}.json")
            lp = A / "layers" / f"{bb}_{ro.replace('lastmidhalf','last-mid-half').replace('lastmid','last-mid')}_s0.json"
            l = json.load(open(lp)) if lp.exists() else {}
            if not d:
                rows.append((bb, ro, None, None, None, None, None)); continue
            rows.append((bb, ro, d["standalone_mean"]["dev_v31"], d["standalone_mean"]["ffpp_val_auroc"],
                         d["fused_mean"]["loo"]["APP"], l.get("ffpp_val_jpeg:30"), l.get("ffpp_val_resize:0.35")))
    return rows


def main() -> int:
    L = ["# CROSS-EXAM upgrade report", "",
         "Brief: `tbiom/docs/discern-v2-crossexam-upgrade-brief.md`. Code in `upgrade/`, evidence in",
         "`analysis/upgrade/`. Generated by `upgrade/part8_assemble.py`; unrun cells read `TODO(run)`",
         "and are never filled in from a neighbouring number.", ""]

    # ---- 1. decision trail
    L += ["## 1. Decision trail", "", "| rule | verdict | evidence |", "|---|---|---|"]
    sc = {n: r for n, *r in [(r[0], *r[1:]) for r in screen_table()]}

    def loo(n):
        return sc.get(n, [None] * 5)[4]

    best_frozen = max([n for n in ("clip", "dinov3", "pe", "pe_spatial", "pe_core_l") if loo(n) is not None],
                      key=loo, default=None)
    L.append(f"| Part 3b shortlist: top two by incremental contribution over LFS and TD | "
             f"**{'PE-Core-L and CLIP' if best_frozen else TODO}** | `screen_*.json` |")
    ro = {(b, r): v for b, r, *v in readout_table()}
    pe_last, pe_lmh = ro.get(("pe_core_l", "last")), ro.get(("pe_core_l", "lastmidhalf"))
    if pe_last and pe_lmh and None not in (pe_last[2], pe_lmh[2], pe_last[3], pe_lmh[3]):
        c1 = pe_lmh[2] > pe_last[2]
        c2 = (pe_lmh[3] >= pe_last[3] - 0.01) and (pe_lmh[4] >= pe_last[4] - 0.01)
        L.append(f"| Part 3d keep rule on PE-Core (beat `last` on contribution AND stay within 0.01 processed) | "
                 f"**{'PASS' if (c1 and c2) else 'FAIL'}** (contribution {pe_lmh[2]:+.4f} vs {pe_last[2]:+.4f}; "
                 f"jpeg30 {pe_lmh[3]:.4f} vs {pe_last[3]:.4f}) | `screen_pe_core_l-*.json` |")
    cl_last, cl_lmh = ro.get(("clip", "last")), ro.get(("clip", "lastmidhalf"))
    if cl_last and cl_lmh and None not in (cl_last[2], cl_lmh[2]):
        L.append(f"| Part 3d keep rule on CLIP | **{'PASS' if cl_lmh[2] > cl_last[2] else 'FAIL'}** "
                 f"(contribution {cl_lmh[2]:+.4f} vs {cl_last[2]:+.4f}) | `screen_clip-*.json` |")
    L.append(f"| Part 1, J1s | **not runnable** | no Option B addition and no definition of J1s exists "
             f"in the repository or the session transcript |")
    for part, f in (("Part 4 keep rule", "part4_rows.json"), ("Part 5 keep rule", "consistency/summary.json"),
                    ("Part 6c keep rule", "regional/summary.json"), ("Part 8 success criterion", "final/summary.json")):
        L.append(f"| {part} | {TODO} | `{f}` |")
    L.append("")

    # ---- 2. diagnostics
    L += ["## 2. Diagnostics", ""]
    t = j("part2a_threshold.json")
    if t:
        L += ["### 2a. Threshold transfer versus ranking", "",
              "A set with healthy AUROC but high FPR at the FF++ threshold has a threshold-transfer",
              "problem, not a ranking one. Analysis only; no rule reads it.", "",
              "| set | AUROC | FPR@FF++ tau | FPR@own EER | gap | ECE |", "|---|---:|---:|---:|---:|---:|"]
        for n, r in sorted(t["sets"].items(), key=lambda kv: -kv[1]["threshold_transfer_gap"]):
            L.append(f"| {n} | {r['auroc']:.4f} | {r['fpr_at_ffpp_tau']:.4f} | {r['fpr_at_own_eer']:.4f} | "
                     f"{r['threshold_transfer_gap']:+.4f} | {r['ece']:.4f} |")
        L.append("")
    else:
        L += [f"### 2a. {TODO}", ""]
    hm = j("part1_hinge_margin.json")
    if hm:
        L += ["### Part 1 residue: the hinge margin qualifies G0b", "",
              "G0b reports the hinge active on 65% of training samples under equal trust, but `active`",
              "only means `kappa - u_f > 0`. The margin's own distribution:", "",
              "| weights | active | p50 | share above 1e-2 |", "|---|---:|---:|---:|"]
        for n, r in hm["weight_sets"].items():
            L.append(f"| {n} | {r['n_active']} | {r['p50']:.5f} | {r['frac_active_above_1e-2']:.3f} |")
        L.append("")
    L += [f"### 2b. Feature-space factor profile — {TODO}", ""]

    # ---- 3. screen and readout tables
    L += ["## 3. Screen, adaptation and layer readout", "",
          "### Spatial screen and adaptation", "",
          "| candidate | dev v3.1 | FF++ val | fused | FPR real | incremental over LFS+TD |",
          "|---|---:|---:|---:|---:|---:|"]
    for n, dv, ff, fu, fp, lo in screen_table():
        L.append(f"| {n} | {fmt(dv)} | {fmt(ff)} | {fmt(fu)} | {fmt(fp)} | "
                 + (f"{lo:+.4f}" if lo is not None else TODO) + " |")
    L += ["", "### Layer readout (Part 3d)", "",
          "| backbone | readout | dev v3.1 | FF++ val | incremental | jpeg q30 | resize 0.35 |",
          "|---|---|---:|---:|---:|---:|---:|"]
    for b, r, dv, ff, lo, jp, rs in readout_table():
        L.append(f"| {b} | {r} | {fmt(dv)} | {fmt(ff)} | " + (f"{lo:+.4f}" if lo is not None else TODO)
                 + f" | {fmt(jp)} | {fmt(rs)} |")
    L += ["", "### Adapted rows", "", "| run | readout | best epoch | dev v3.1 (full) | VALmix-v2 | FF++ val |",
          "|---|---|---:|---:|---:|---:|"]
    for p in sorted((A / "adapt").glob("*.json")) if (A / "adapt").exists() else []:
        d = json.load(open(p))
        L.append(f"| {d['backbone']}_{d['recipe']}_s{d['seed']} | {d.get('readout','last')} | "
                 f"{d['best_epoch']} | {fmt(d.get('dev_v31_full'))} | {fmt(d.get('valmixv2_full'))} | "
                 f"{fmt(d.get('ffpp_val_auroc_full'))} |")
    L += ["", f"## 4. Suppression study — {TODO}", "", f"## 5. Consistency — {TODO}", "",
          f"## 6. Video view — see `heads/view_vjepa2_*.json`; regional rows {TODO}", "",
          f"## 7. Final development and test tables — {TODO}", "",
          "## 8. Negative results", "",
          "| finding | number that decided it |", "|---|---|",
          "| J1s and the Option B addition do not exist, so that run cannot be made | no definition in repo or transcript |",
          "| Meta has not released V-JEPA 2.1; the only hub `2.1` is third-party with custom code at 384 | substituted official ViT-H at 256 |",
          "| PE-Spatial has no checkpoint at or below the 256 crop | smallest loadable is base/512, 100% upsampled at 2.0x |",
          "| DINOv3 is more independent than CLIP yet fuses worse | contribution -0.0002, weight zeroed in 3.67/5 folds |",
          "",
          "## 9. Slide consistency", "",
          "The talk slides describe *nuisance-purified appearance on I-JEPA*. On the evidence so far the",
          f"selected spatial backbone is **{'PE-Core L14-336' if best_frozen == 'pe_core_l' else TODO}**, not I-JEPA, and the",
          "nuisance-purification claim depends on Part 4, which is still " + TODO + ".",
          "If that holds, the accurate slide title is the backbone actually selected.", ""]
    (A / "UPGRADE-REPORT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {A/'UPGRADE-REPORT.md'} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
