#!/usr/bin/env python3
"""Tasks 1 and 2 of the leakage audit: video-level inventory, dataset table and the three overlap matrices.

    OMP_NUM_THREADS=4 python audit/leakage/overlap.py

Read-only. Counts come from the manifests the deployed configuration names; identifier rules come from
`audit/leakage/keys.py`, which self-tests against real manifest lines.
"""
from __future__ import annotations
import csv, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import keys as K

ROOT, EXT = Path("/data/umar/Repos/DFB_NeSyNS"), Path("/data/umar/Repos/DISCERN_Ext")
OUT, SPL = ROOT / "audit/leakage", EXT / "eval_adaptation/data/splits"
CFG = EXT / "eval_adaptation/configs/warm_dicome_gate_seed42.yaml"
TEN = ["CDFv2", "CDFv3", "DFD", "DFDC", "DFDCP", "DFEval24", "FFIW", "KoDF", "IDForge", "DFDM"]
REAL = re.compile(r"real", re.I)
# exclusions the brief asks to be recorded
EXCLUSIONS = {"CDFv3": "IP_LAP subset excluded", "KoDF": "audio-driven and adversarial subsets excluded",
              "IDForge": "restricted to InfoSwap, Roop and SimSwap"}


def group(name: str, files: list[Path]):
    """-> {'videos': {v: frames}, 'sources': set, 'identities': set, 'real': n, 'fake': n, 'manifests': [...]}"""
    g = {"videos": {}, "sources": set(), "identities": set(), "real": 0, "fake": 0, "manifests": []}
    for p in files:
        if not p.exists():
            continue
        g["manifests"].append(str(p.relative_to(EXT)))
        vids, src, ids = K.manifest_keys(p)          # each line's own origin rule; handles both pool depths
        is_real = bool(REAL.search(p.stem))
        for v, n in vids.items():
            g["videos"][f"{p.stem}/{v}"] = n
            g["real" if is_real else "fake"] += 1
        g["sources"].update(src); g["identities"].update(ids)
    return g


def main():
    cfg = CFG.read_text()
    groups = {}

    def block(blk):
        m = re.search(rf"^{blk}:\n((?:- .*\n)+)", cfg, re.M)
        return [EXT / l.lstrip("- ").strip() for l in (m.group(1).strip().split("\n") if m else [])]

    groups["TRAIN FFpp c23 (spatial views + video view)"] = group("FFpp_train", block("trn_files"))
    groups["THRESHOLD FFpp c23 val"] = group("FFpp_val", block("val_files"))
    for n in ("VALmix", "VALmixV2"):
        d = SPL / n
        groups[f"DEV POOL {n}"] = group(n, sorted(d.glob("*.txt")) if d.exists() else [])
    for ds in TEN:
        d = SPL / ds
        groups[f"TEST {ds}"] = group(ds, sorted(d.glob("*.txt")) if d.exists() else [])
    d = SPL / "DF40"
    groups["DF40 evaluation (41 sets)"] = group("DF40", sorted(d.glob("*.txt")) if d.exists() else [])

    # ---- inventory + dataset table
    inv, dt = [], []
    for name, g in groups.items():
        nf = sum(g["videos"].values())
        nv = len(g["videos"])
        inv.append({"split": name, "videos": nv, "real": g["real"], "fake": g["fake"],
                    "source_videos": len(g["sources"]), "identities": len(g["identities"]) or "not available",
                    "total_frames": nf, "frames_per_video": round(nf / nv, 2) if nv else 0,
                    "manifests": len(g["manifests"]),
                    "key_type": "video ID + source video" + ("" if g["identities"] else " (identity not available)")})
        dt.append({"split": name, "videos": nv, "real": g["real"], "fake": g["fake"],
                   "frames_per_video": round(nf / nv, 2) if nv else 0, "total_frames": nf,
                   "exclusion": EXCLUSIONS.get(name.replace("TEST ", ""), "")})
    for f, rows, cols in (("inventory.csv", inv, list(inv[0])), ("dataset_table.csv", dt, list(dt[0]))):
        with open(OUT / f, "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=cols); w.writeheader(); w.writerows(rows)

    tex = ["% generated by audit/leakage/overlap.py", "\\begin{tabular}{lrrrrrl}", "\\toprule",
           "Split & Videos & Real & Fake & Frames/video & Frames & Exclusion \\\\", "\\midrule"]
    for r in dt:
        tex.append(f"{r['split'].replace('_', chr(92) + '_')} & {r['videos']} & {r['real']} & {r['fake']} & "
                   f"{r['frames_per_video']} & {r['total_frames']} & {r['exclusion'] or '--'} \\\\")
    tex += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "dataset_table.tex").write_text("\n".join(tex) + "\n")

    # ---- overlap matrices
    FIT = ["TRAIN FFpp c23 (spatial views + video view)", "THRESHOLD FFpp c23 val",
           "DEV POOL VALmix", "DEV POOL VALmixV2"]
    EVAL = [f"TEST {d}" for d in TEN] + ["DF40 evaluation (41 sets)"]
    levels = {"video": lambda g: {v.split("/", 1)[1] for v in g["videos"]},
              "source": lambda g: g["sources"], "identity": lambda g: g["identities"]}
    nonzero = []
    for lvl, get in levels.items():
        rows = []
        for a in FIT:
            r = {"fitting_split": a}
            for b in EVAL:
                A, B = get(groups[a]), get(groups[b])
                n = len(A & B)
                r[b] = n
                if n:
                    nonzero.append({"level": lvl, "fitting_split": a, "eval_split": b, "n": n,
                                    "examples": ", ".join(sorted(A & B)[:5])})
            rows.append(r)
        with open(OUT / f"overlap_{lvl}.csv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=["fitting_split"] + EVAL); w.writeheader(); w.writerows(rows)
    with open(OUT / "overlap_nonzero.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["level", "fitting_split", "eval_split", "n", "examples"])
        w.writeheader(); w.writerows(nonzero)
    json.dump({k: {"videos": len(v["videos"]), "sources": len(v["sources"]),
                   "identities": len(v["identities"]), "manifests": v["manifests"]}
               for k, v in groups.items()}, open(OUT / "groups_summary.json", "w"), indent=1)
    print(f"{len(inv)} splits inventoried; {len(nonzero)} nonzero overlap cells")
    for r in nonzero:
        print(f"  [{r['level']:8s}] {r['fitting_split']:44s} x {r['eval_split']:28s} {r['n']:6d}  e.g. {r['examples'][:60]}")


if __name__ == "__main__":
    main()
