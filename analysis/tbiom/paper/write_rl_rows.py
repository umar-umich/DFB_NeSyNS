#!/usr/bin/env python3
"""Append the RL pilot rows to the acquisition table and settle the two provenance questions."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

R = Path("tbiom/reports")


def main():
    D = json.load(open(R / "EXP_ACQUISITION_RL.json"))
    A = json.load(open(R / "EXP_ACQUISITION_INTERVALS.json"))
    S = A["splits"]
    m = lambda pol, k: float(np.mean([s["policies"][pol][k] for s in S]))
    ci = lambda pol, i: float(np.mean([s["policies"][pol]["ci"][i] for s in S]))

    def arm(name):
        Ar = [f["arms"][name] for f in D["folds"]]
        g = lambda k: float(np.mean([np.mean([s[k] for s in a["per_seed"]]) for a in Ar]))
        return {"auroc": g("auroc"), "delta": g("delta"), "fpr": g("fpr"), "clips": g("clips_per_video"),
                "lo": float(np.mean([np.mean([s["ci"][0] for s in a["per_seed"]]) for a in Ar])),
                "hi": float(np.mean([np.mean([s["ci"][1] for s in a["per_seed"]]) for a in Ar])),
                "spread": float(np.mean([np.ptp([s["auroc"] for s in a["per_seed"]]) for a in Ar])),
                "train_s": float(sum(s["train_s"] for a in Ar for s in a["per_seed"])),
                "costs": [a["cost"] for a in Ar],
                "curves": np.stack([np.array(c) for a in Ar for c in a["curves"]])}

    RL = {n: arm(n) for n in ("PPO (k=1)", "PPO (k=2)", "REINFORCE (k=1)")}
    N = [f["null_oracle"] for f in D["folds"]]
    nm, nsd = float(np.mean([x["auroc_mean"] for x in N])), float(np.mean([x["auroc_sd"] for x in N]))
    nmin, nmax = float(np.mean([x["auroc_min"] for x in N])), float(np.mean([x["auroc_max"] for x in N]))
    base = float(np.mean([x["base"] for x in N]))

    L = ["# Acquisition table with the RL pilot rows", "",
         "Cached outputs only; no detector was retrained. Environment, folds, windows, aggregation rule (`conf`), "
         "DS-R fusion and frozen threshold are the ones in `EXP_ACQUISITION_PILOT.md`. Generated by "
         "`analysis/tbiom/acquisition/rl_pilot.py`.", "",
         "**Provenance note.** The frozen go/no-go in `tbiom/docs/decision-2026-09-18.md` concluded *do not proceed "
         "to PPO* because its learnability condition failed. This pilot was requested afterwards and is an explicit "
         "override of that gate. It is reported as a pilot, not as a satisfied criterion.", "",
         "## 1. The table", "",
         "| policy | method | extra clips / video | AUROC | $\\Delta$ vs no extra clip | 95% CI | FPR @ $\\tau$ |",
         "|---|---|---:|---:|---:|---|---:|"]
    ROWS = [("no extra clip (k=0)", "--", "no acquisition", 0),
            ("random extra clip (k=1)", "random", "random", 1),
            ("evenly spaced extra clips w0+w2 (k=2)", "fixed", "fixed pair $w_0{+}w_2$", 2),
            ("quality-based choice (k=1)", "heuristic on label-free descriptors", "quality-based", 1),
            ("learned one-step choice (k=1)",
             "**supervised, full-information action-value regression** (gradient-boosted; trained on the log-loss "
             "gain of *every* window, then argmax). Not a bandit, not RL.", "learned one-step", 1),
            ("learned two-step choice (k=2)",
             "**same one-step model, static top-2**: the two highest predicted gains taken from the initial state, "
             "with no re-planning after the first observation.", "learned two-step", 2),
            ("oracle, true label (k=1)", "oracle", "oracle (true label)", 1),
            ("oracle, true label (k=2)", "oracle", "oracle (true label)", 2),
            ("oracle, scores shuffled from other videos (k=1)", "null oracle", "oracle (shuffled scores)", 1)]
    for key, meth, lab, k in ROWS:
        L.append(f"| {lab} | {meth} | {k} | {m(key, 'auroc'):.4f} | {m(key, 'delta'):+.4f} | "
                 f"[{ci(key, 0):+.4f}, {ci(key, 1):+.4f}] | {m(key, 'fpr'):.3f} |")
    L.append("| | | | | | | |")
    for n, meth in (("PPO (k=1)", "**PPO**, actor-critic MLP (2$\\times$64 tanh), clip 0.2, 3 seeds"),
                    ("PPO (k=2)", "**PPO**, same network, budget 2, 3 seeds"),
                    ("REINFORCE (k=1)", "**REINFORCE** with a learned baseline, same network, 3 seeds")):
        r = RL[n]
        L.append(f"| **{n}** | {meth} | {r['clips']:.2f} | {r['auroc']:.4f} | {r['delta']:+.4f} | "
                 f"[{r['lo']:+.4f}, {r['hi']:+.4f}] | {r['fpr']:.3f} |")
    L += ["", "The RL rows report the mean over 3 seeds $\\times$ 5 folds; every other row is the mean over 5 folds. "
          "The extra-clips column for the RL rows is *measured*, not fixed: the policy may stop, so it is below the "
          "budget it was given.", "",
          "## 2. What the RL policies learned", "",
          "| arm | cost chosen per fold | clips/video | seed spread in AUROC | training time (all seeds, all folds) |",
          "|---|---|---:|---:|---:|"]
    for n, r in RL.items():
        L.append(f"| {n} | {', '.join(str(c) for c in r['costs'])} | {r['clips']:.2f} | {r['spread']:.4f} | "
                 f"{r['train_s']:.0f} s |")
    L += ["", f"Total wall clock for the whole pilot, including the cost search: **{D['wall_clock_s'] / 60:.1f} "
          f"minutes** on CPU, against a four-hour budget. {D['iters']} policy-gradient iterations per run, "
          f"{D['seeds']} seeds, 5 folds, 3 arms.", "",
          "The cost per extra clip was selected on the **fitting folds only**, by fitting-fold AUROC of the greedy "
          f"policy, over the grid {D['cost_grid']}. It came out at the top of the grid (0.02) in 12 of the 15 "
          "fold-arm cells, i.e. the fitting folds prefer a policy that mostly declines to acquire.", "",
          "**The policies learn to stop.** At budget 1 PPO uses 0.68 clips per video and REINFORCE 0.77; at budget 2 "
          "PPO uses 0.93 of a possible 2. That is why they beat every other learned row in the table: the supervised "
          "selector is forced to spend its budget, while an RL policy can decline. The closer these policies get to "
          "never acquiring, the closer their AUROC gets to the no-acquisition baseline — which is the ceiling here, "
          "not the floor.", "",
          "**None of them beats not acquiring.** PPO at budget 1 is $-0.0050$ with the interval excluding zero, and "
          "REINFORCE is $-0.0066$, also excluding zero. PPO at budget 2 is $-0.0016$ with the interval spanning "
          "zero, i.e. statistically indistinguishable from doing nothing, which is the best outcome available to a "
          "policy in this environment.", "",
          "## 3. Training reward curves", "",
          "Mean episode reward (log-loss drop minus cost), averaged over 3 seeds $\\times$ 5 folds.", "",
          "| arm | iter 1 | iter 10 | iter 20 | iter 40 | iter 60 | sd across runs at iter 60 |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for n, r in RL.items():
        c = r["curves"]
        L.append(f"| {n} | " + " | ".join(f"{c[:, i].mean():+.4f}" for i in (0, 9, 19, 39, 59))
                 + f" | {c[:, -1].std():.4f} |")
    L += ["", "Reward rises steadily for all three arms, so the optimisation is working. It rises mostly by learning "
          "to *avoid the cost term*, not by finding informative windows -- which is exactly what the clips-per-video "
          "column shows.", "",
          "## 4. The two provenance questions", "",
          "**(a) What are the existing learned rows?** The one-step row is a **supervised, full-information "
          "action-value regressor**: a `GradientBoostingRegressor` fitted on the fitting fold against the log-loss "
          "gain of *every* candidate window, then applied by argmax. It is not a contextual bandit -- a bandit "
          "observes the reward of the arm it pulled and nothing else, whereas this model is trained on all four arms' "
          "outcomes. The two-step row is **not** sequential greedy: it takes the first and second highest predicted "
          "gains from the same model evaluated once in the initial state, with no re-planning after the first "
          "observation. The labels in the table above have been corrected accordingly.", "",
          f"**(b) Is the shuffled-score oracle gain $+0.0806$ or $+0.0788$?** Both, and neither is wrong. Both used "
          f"the **`conf`** aggregation rule; they differ only in the random permutation drawn. Over 20 permutations "
          f"per fold the null oracle scores {nm:.4f} $\\pm$ {nsd:.4f} (min {nmin:.4f}, max {nmax:.4f}) against a "
          f"no-acquisition baseline of {base:.4f}, i.e. a gain of **{nm - base:+.4f} $\\pm$ {nsd:.4f}**. The "
          f"published $+0.0788$ and the recomputed $+0.0806$ are two draws from that distribution. The figure to "
          f"quote is the permutation mean, {nm - base:+.4f}.", "",
          "For completeness, the aggregation rule behind every number in this document is `conf`, the "
          "vacuity-weighted within-branch mean, which is what `EXP_ACQUISITION_PILOT.md` reports in its section 1 "
          "table. The `mean` and `max` rules appear only in that report's section 0 comparison.", "",
          "## 5. Verdict", "",
          "The pilot ran to completion inside the budget and changes nothing. No policy class tried here -- "
          "supervised full-information, PPO at two budgets, or REINFORCE -- improves on not acquiring an extra clip. "
          "The best result available is to spend nothing, and the policies that come closest to the baseline are the "
          "ones that learn to stop. Combined with the null oracle's $+0.079$, which is larger than the true-label "
          "oracle's $+0.031$ and is by construction uninformative, the evidence says the apparent headroom in this "
          "environment is selection on labels among correlated scores rather than information a policy could use.", ""]
    (R / "EXP_ACQUISITION_RL.md").write_text("\n".join(L) + "\n")
    print("wrote", R / "EXP_ACQUISITION_RL.md")


if __name__ == "__main__":
    main()
