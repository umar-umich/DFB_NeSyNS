#!/usr/bin/env python3
"""Generate every LaTeX table in the T-BIOM manuscript from the committed result files.

    OMP_NUM_THREADS=4 python analysis/tbiom/paper/build_tables.py

No number in the paper is typed by hand. Each table carries a comment naming the JSON it came from, so a value in the
manuscript can be traced to the report that produced it. The proposed method is PCR6+-R (direct three-source PCR6+
after the evidence-scaling reliability discount) at detector configuration `42`, the deployed reference.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

R, OUT = Path("tbiom/reports"), Path("tbiom/paper/tables")
CFG = "42"
OURS = "PCR6P-R"
TESTS = ["CDFv2", "CDFv3", "DFD", "DFDC", "DFDCP", "DFEval24", "FFIW", "KoDF", "IDForge", "DFDM"]
SHORT = {"CDFv2": "CDF-v2", "CDFv3": "CDF-v3", "DFD": "DFD", "DFDC": "DFDC", "DFDCP": "DFDCP",
         "DFEval24": "DFEval24", "FFIW": "FFIW", "KoDF": "KoDF", "IDForge": "IDForge", "DFDM": "DFDM"}
CELLS = (("face swap", "cdf", "Swap / CDF"), ("face swap", "ff", "Swap / FF++"),
         ("reenactment", "cdf", "Reenact. / CDF"), ("reenactment", "ff", "Reenact. / FF++"))
PRETTY = {"blendface": "BlendFace", "e4s": "e4s", "facedancer": "FaceDancer", "faceswap": "FaceSwap",
          "fsgan": "FSGAN", "inswap": "InSwapper", "mobileswap": "MobileFaceSwap", "simswap": "SimSwap",
          "uniface": "UniFace", "deepfacelab": "DeepFaceLab", "danet": "DaNet", "facevid2vid": "FaceVid2Vid",
          "fomm": "FOMM", "hyperreenact": "HyperReenact", "lia": "LIA", "mcnet": "MCNet", "MRAA": "MRAA",
          "one_shot_free": "One-Shot Free", "pirender": "PIRender", "sadtalker": "SadTalker", "tpsm": "TPSM"}
BASE_NAME = {"R0 (v3.1, ep 6)": "DISCERN (conf.\\ version)", "DiCoME (our training, v3.1, ep 5)": "DiCoME~\\cite{kang2026dicome}",
             "GenD-CLIP": "GenD-CLIP~\\cite{yermakov2026deepfake}", "GenD-PE": "GenD-PE~\\cite{yermakov2026deepfake}",
             "GenD-DINO": "GenD-DINO~\\cite{yermakov2026deepfake}", "Effort": "Effort~\\cite{yan2025effort}",
             "ForAda": "ForAda~\\cite{cui2025forada}", "FSFM": "FSFM~\\cite{wang2025fsfm}",
             "FSFM-Adapter": "FSFM-Adapter~\\cite{wang2025fsfm}"}
DROP = {"A (v3.1, ep 5)", "B (v3.1, ep 8)", "C (v3.1, ep 2)"}      # internal SBI arms, not comparators


def js(n):
    p = R / f"{n}.json"
    return json.load(open(p)) if p.exists() else None


def w(name, body, note):
    (OUT / f"{name}.tex").write_text(f"% generated by analysis/tbiom/paper/build_tables.py\n% source: {note}\n"
                                     + body + "\n")
    print("wrote", OUT / f"{name}.tex")


def f4(x):
    return "--" if x is None or x != x else f"{x:.4f}"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    E = js("EXP_PCR6P_EXPOSED")[CFG]
    Dv = js("EXP_PCR6P_DEVELOPMENT")[CFG]
    B = js("BASELINE_MATRIX")
    D40 = js("EXP_DF40_CROSS_MANIPULATION")
    meta = json.load(open("logs/tbiom/df40/meta.json"))
    t = lambda arm, tn, k="auroc": float(np.mean([r[k] for r in E["tests"][arm][tn]]))
    g = lambda arm, n: float(np.mean(E["df40"][arm][n]))
    cell = lambda arm, fam, src: float(np.mean([g(arm, n) for n in E["df40"][arm]
                                                if meta[n]["family"] == fam and meta[n]["source"] == src]))

    # ---------------------------------------------------------------- Table I: cross-dataset
    rows = []
    for n, d in B.items():
        if n in DROP:
            continue
        rows.append((BASE_NAME.get(n, n), [d[x]["video"] if x in d else None for x in TESTS]))
    ours = [t(OURS, x) for x in TESTS]
    body = ["\\begin{table*}[t]", "\\centering",
            "\\caption{Cross-dataset generalisation, video-level AUROC. All systems are evaluated locally on the "
            "same videos with the same aggregation; no number is taken from a published table. Our rows are means "
            "over the five reliability-fitting folds. Best per column in \\textbf{bold}.}",
            "\\label{tab:crossdataset}", "\\setlength{\\tabcolsep}{4pt}", "\\small",
            "\\begin{tabular}{l" + "c" * len(TESTS) + "c}", "\\toprule",
            "Method & " + " & ".join(SHORT[x] for x in TESTS) + " & Mean \\\\", "\\midrule"]
    best = [max([r[1][i] for r in rows if r[1][i] is not None] + [ours[i]]) for i in range(len(TESTS))]
    for nm, v in sorted(rows, key=lambda r: -np.mean([x for x in r[1] if x is not None])):
        cells = [("\\textbf{%s}" % f4(x)) if x is not None and abs(x - best[i]) < 1e-9 else f4(x)
                 for i, x in enumerate(v)]
        body.append(f"{nm} & " + " & ".join(cells) + f" & {f4(np.mean([x for x in v if x is not None]))} \\\\")
    body.append("\\midrule")
    cells = [("\\textbf{%s}" % f4(x)) if abs(x - best[i]) < 1e-9 else f4(x) for i, x in enumerate(ours)]
    body.append("\\textbf{Ours (PCR6$^+$-R)} & " + " & ".join(cells)
                + f" & \\textbf{{{f4(np.mean(ours))}}} \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    w("tab_crossdataset", "\n".join(body), "EXP_PCR6P_EXPOSED.json (ours), BASELINE_MATRIX.json (comparators)")

    # ---------------------------------------------------------------- Table II: DF40 family summary
    dic = {n: D40[n]["dicome"] for n in D40 if "dicome" in D40[n]}
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{Cross-manipulation on DF40. Each generator is scored against the genuine pool DF40 ships for "
            "its source. DiCoME is our own trained checkpoint replayed through its own fusion, so both systems see "
            "identical videos with identical aggregation.}",
            "\\label{tab:df40family}", "\\small", "\\begin{tabular}{lccrc}", "\\toprule",
            "Family / source & Gen. & \\textbf{Ours} & DiCoME & $\\Delta$ \\\\", "\\midrule"]
    for fam, src, lab in CELLS:
        ns = [n for n in E["df40"][OURS] if meta[n]["family"] == fam and meta[n]["source"] == src]
        o, d = np.mean([g(OURS, n) for n in ns]), np.mean([dic[n] for n in ns])
        body.append(f"{lab} & {len(ns)} & \\textbf{{{o:.4f}}} & {d:.4f} & ${o - d:+.4f}$ \\\\")
    allns = list(E["df40"][OURS])
    o = np.mean([np.mean([g(OURS, n) for n in allns if meta[n]["family"] == f and meta[n]["source"] == s])
                 for f, s, _ in CELLS])
    d = np.mean([np.mean([dic[n] for n in allns if meta[n]["family"] == f and meta[n]["source"] == s])
                 for f, s, _ in CELLS])
    body.append("\\midrule")
    body.append(f"Family-balanced & 41 & \\textbf{{{o:.4f}}} & {d:.4f} & ${o - d:+.4f}$ \\\\")
    om, dm = np.mean([g(OURS, n) for n in allns]), np.mean([dic[n] for n in allns])
    wins = sum(g(OURS, n) > dic[n] for n in allns)
    body.append(f"Generator-macro & 41 & \\textbf{{{om:.4f}}} & {dm:.4f} & ${om - dm:+.4f}$ \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_df40family", "\n".join(body), "EXP_PCR6P_EXPOSED.json + EXP_DF40_CROSS_MANIPULATION.json")

    # ---------------------------------------------------------------- Table III: per generator
    body = ["\\begin{table*}[t]", "\\centering",
            "\\caption{Per-generator cross-manipulation AUROC on all 41 DF40 generator--source entries, with the "
            "per-view scores of the proposed system. Views: $T$ temporal, $A$ appearance, $O$ off-manifold. "
            "Generators where both spatial views are near chance are the ones the temporal view rescues.}",
            "\\label{tab:df40gen}", "\\setlength{\\tabcolsep}{3.5pt}", "\\footnotesize",
            "\\begin{tabular}{llcccc@{\\hskip 10pt}llcccc}", "\\toprule",
            "\\multicolumn{6}{c}{\\textbf{Face swap}} & \\multicolumn{6}{c}{\\textbf{Face reenactment}} \\\\",
            "\\cmidrule(lr){1-6}\\cmidrule(lr){7-12}",
            "Gen. & Src & \\textbf{Ours} & DiCoME & $T$ & $A$/$O$ & Gen. & Src & \\textbf{Ours} & DiCoME & $T$ & $A$/$O$ \\\\",
            "\\midrule"]
    sw = sorted([n for n in allns if meta[n]["family"] == "face swap"],
                key=lambda n: (meta[n]["source"], meta[n]["method"]))
    re = sorted([n for n in allns if meta[n]["family"] == "reenactment"],
                key=lambda n: (meta[n]["source"], meta[n]["method"]))
    V = {n: D40[n] for n in D40}
    for i in range(max(len(sw), len(re))):
        def blk(lst):
            if i >= len(lst):
                return " & " * 5 + " "
            n = lst[i]; m = meta[n]; v = V[n]
            return (f"{PRETTY.get(m['method'], m['method'])} & {m['source']} & \\textbf{{{g(OURS, n):.3f}}} & "
                    f"{dic[n]:.3f} & {v['view_T']:.3f} & {v['view_APP']:.2f}/{v['view_OM']:.2f}")
        body.append(blk(sw) + " & " + blk(re) + " \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    w("tab_df40gen", "\n".join(body), "EXP_PCR6P_EXPOSED.json + EXP_DF40_CROSS_MANIPULATION.json")

    # ---------------------------------------------------------------- Table IV: view necessity
    dm_ = lambda arm, k: float(np.mean([r["arms"][arm][k] for r in Dv if k in r["arms"][arm]]))
    bal = lambda arm: float(np.mean([cell(arm, f, s) for f, s, _ in CELLS]))
    LADDER = [("T only", "$T$"), ("APP+OM (PCR6+)", "$A{+}O$"), ("T+APP (PCR6+)", "$T{+}A$"),
              ("T+OM (PCR6+)", "$T{+}O$"), (OURS, "$T{+}A{+}O$ (deployed)")]
    LADDER = [(a, l) for a, l in LADDER if a in E["tests"]]
    cols = [("Dev.\\ v3.1", lambda a: dm_(a, "v31")), ("Reenact.", lambda a: dm_(a, "reenactment")),
            ("10-set", lambda a: np.mean([t(a, x) for x in TESTS])), ("DF40", bal)]
    vals = {lab: [fn(a) for a, _l in LADDER] for lab, fn in cols}
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{View subsets, each fitted and scored identically and fused with the proposed operator; only "
            "the view set changes. Best per column in \\textbf{bold}. These are means taken across manipulation "
            "families and partly cancel the per-family effects; Table~\\ref{tab:viewrole} resolves them.}",
            "\\label{tab:views}", "\\small", "\\begin{tabular}{lcccc}", "\\toprule",
            "Views & " + " & ".join(c[0] for c in cols) + " \\\\", "\\midrule"]
    for i, (a, lab) in enumerate(LADDER):
        cells = []
        for c, _fn in cols:
            v = vals[c][i]
            cells.append(("\\textbf{%.4f}" % v) if abs(v - max(vals[c])) < 1e-9 else f"{v:.4f}")
        body.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_views", "\n".join(body), "EXP_PCR6P_DEVELOPMENT.json + EXP_PCR6P_EXPOSED.json")

    # ---------------------------------------------------------------- Table IVb: what each view contributes where
    # Each row removes one view from the deployed set and reports the change. The point of the table is that the
    # three views divide the work by manipulation family rather than duplicating it.
    GROUPS = [("Swap-dominated sets", ["CDFv2", "DFD", "DFDC", "DFDCP", "IDForge", "DFDM"]),
              ("Reenactment-heavy sets", ["CDFv3", "KoDF"]),
              ("In-the-wild sets", ["FFIW", "DFEval24"])]
    REMOVE = [("T+OM (PCR6+)", "$-A$"), ("T+APP (PCR6+)", "$-O$"), ("APP+OM (PCR6+)", "$-T$")]
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{What each view contributes, and where. Each column removes one view from the deployed set "
            "and reports the change in mean video AUROC. The views divide the work by manipulation family: the "
            "appearance view earns its place on swap and in-the-wild content, the off-manifold and temporal views "
            "on reenactment.}",
            "\\label{tab:viewrole}", "\\small", "\\begin{tabular}{lcccc}", "\\toprule",
            "Evaluation group & Full & $-A$ & $-O$ & $-T$ \\\\", "\\midrule"]
    for lab, sets in GROUPS:
        full = np.mean([t(OURS, x) for x in sets])
        cells = [f"{full:.4f}"]
        for arm, _l in REMOVE:
            cells.append(f"${np.mean([t(arm, x) for x in sets]) - full:+.4f}$" if arm in E["tests"] else "--")
        body.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    body.append("\\midrule")
    for fam, lab in (("face swap", "DF40 face swap"), ("reenactment", "DF40 reenactment")):
        ns = [n for n in E["df40"][OURS] if meta[n]["family"] == fam]
        full = np.mean([g(OURS, n) for n in ns])
        cells = [f"{full:.4f}"]
        for arm, _l in REMOVE:
            cells.append(f"${np.mean([g(arm, n) for n in ns]) - full:+.4f}$" if arm in E["df40"] else "--")
        body.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_viewrole", "\n".join(body), "EXP_PCR6P_EXPOSED.json")

    # ---------------------------------------------------------------- Table V: operators
    ORD = [(OURS, "\\textbf{PCR6$^+$-R (ours)}"), ("PCR6-R", "PCR6-R"), ("PCR6-pairwise-R", "PCR6-R, pairwise fold"),
           ("Yager-R", "Yager-R"), ("Averaging-R", "Averaging-R~\\cite{xu2024rcml}"), ("Dempster-R", "Dempster-R~\\cite{shafer1976}")]
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{Combination rules over the same three view opinions with the same fitted reliabilities. Only "
            "the operator changes. $\\Delta_{r=0}$ is the largest change caused by removing a view the reliability "
            "fit has already discounted to zero: it is exactly zero only for the proposed rule.}",
            "\\label{tab:operators}", "\\small", "\\begin{tabular}{lcccc}", "\\toprule",
            "Operator & Dev.\\ v3.1 & 10-set & DF40 & $\\Delta_{r=0}$ \\\\", "\\midrule"]
    aud = js("EXP_PCR6P_AUDIT")["notes"]
    z = {OURS: aud["zero_weight_dev_PCR6+"], "PCR6-R": aud["zero_weight_dev_PCR6"]}
    for arm, lab in ORD:
        if arm not in E["tests"]:
            continue
        zz = ("$0$" if z[arm] == 0 else f"${z[arm]:.2f}$") if arm in z else "--"
        body.append(f"{lab} & {dm_(arm, 'v31'):.4f} & {np.mean([t(arm, x) for x in TESTS]):.4f} & "
                    f"{bal(arm):.4f} & {zz} \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_operators", "\n".join(body), "EXP_PCR6P_DEVELOPMENT.json, EXP_PCR6P_EXPOSED.json, EXP_PCR6P_AUDIT.json")

    # ---------------------------------------------------------------- Table VI: reliability + robustness
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{Calibration, selective prediction and processing robustness for the proposed system. "
            "Error-detection AUROC ranks the system's own mistakes; E-AURC is the excess area under the "
            "risk--coverage curve. JPEG and resize are applied at evaluation only; no arm was trained on them.}",
            "\\label{tab:reliability}", "\\small", "\\begin{tabular}{lccccc}", "\\toprule",
            "Set & AUROC & ECE & NLL & err-AUROC & E-AURC \\\\", "\\midrule"]
    for tn in ["CDFv2", "CDFv3", "DFD", "FFIW", "KoDF", "IDForge", "DFDM"]:
        body.append(f"{SHORT[tn]} & {t(OURS, tn):.4f} & {t(OURS, tn, 'ece'):.3f} & {t(OURS, tn, 'nll'):.3f} & "
                    f"{t(OURS, tn, 'err_auroc_vacuity'):.3f} & {t(OURS, tn, 'eaurc_vacuity'):.4f} \\\\")
    body.append("\\midrule")
    for tn, lab in (("CDFv2 jpeg40", "CDF-v2, JPEG q40"), ("CDFv2 rs06", "CDF-v2, resize 0.6"),
                    ("DFDCP jpeg40", "DFDCP, JPEG q40"), ("DFDCP rs06", "DFDCP, resize 0.6")):
        if tn in E["tests"][OURS]:
            body.append(f"{lab} & {t(OURS, tn):.4f} & {t(OURS, tn, 'ece'):.3f} & {t(OURS, tn, 'nll'):.3f} & "
                        f"{t(OURS, tn, 'err_auroc_vacuity'):.3f} & {t(OURS, tn, 'eaurc_vacuity'):.4f} \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_reliability", "\n".join(body), "EXP_PCR6P_EXPOSED.json")

    # ---------------------------------------------------------------- key numbers for the prose
    facts = {"df40_wins": int(sum(g(OURS, n) > dic[n] for n in allns)), "df40_n": len(allns),
             "swap_delta": float(np.mean([g(OURS, n) - dic[n] for n in allns if meta[n]["family"] == "face swap"])),
             "reen_delta": float(np.mean([g(OURS, n) - dic[n] for n in allns if meta[n]["family"] == "reenactment"])),
             "swap_wins": int(sum(g(OURS, n) > dic[n] for n in allns if meta[n]["family"] == "face swap")),
             "swap_n": int(sum(1 for n in allns if meta[n]["family"] == "face swap")),
             "reen_wins": int(sum(g(OURS, n) > dic[n] for n in allns if meta[n]["family"] == "reenactment")),
             "reen_n": int(sum(1 for n in allns if meta[n]["family"] == "reenactment")),
             "tenset": float(np.mean(ours)), "df40_bal": float(bal(OURS)),
             "zero_pcr6": aud["zero_weight_dev_PCR6"], "zero_pcr6p": aud["zero_weight_dev_PCR6+"]}
    chance = [n for n in allns if meta[n]["family"] == "reenactment"
              and max(V[n]["view_APP"], V[n]["view_OM"]) < 0.62]
    facts["chance_generators"] = [{"name": PRETTY.get(meta[n]["method"], meta[n]["method"]), "src": meta[n]["source"],
                                   "T": V[n]["view_T"], "A": V[n]["view_APP"], "O": V[n]["view_OM"],
                                   "ours": g(OURS, n), "dicome": dic[n]} for n in chance]
    json.dump(facts, open("tbiom/paper/tables/key_numbers.json", "w"), indent=1, default=float)
    print("key numbers ->", facts["df40_wins"], "/", facts["df40_n"], "wins;",
          len(chance), "near-chance reenactment generators")


# ===================================================================================================================
# Additional tables (expansion pass). Kept in a separate entry point so the core tables above stay readable.
# ===================================================================================================================
def extras():
    OUT.mkdir(parents=True, exist_ok=True)
    EX = js("EXP_PCR6P_EXPOSED")
    E = EX[CFG]
    Dv = js("EXP_PCR6P_DEVELOPMENT")[CFG]
    F = js("PAPER_EXTRA_FACTS")
    meta = json.load(open("logs/tbiom/df40/meta.json"))
    t = lambda arm, tn, k="auroc": float(np.mean([r[k] for r in E["tests"][arm][tn]]))
    g = lambda cfg, arm, n: float(np.mean(EX[cfg]["df40"][arm][n]))
    cellc = lambda cfg, arm, f, s: float(np.mean([g(cfg, arm, n) for n in EX[cfg]["df40"][arm]
                                                  if meta[n]["family"] == f and meta[n]["source"] == s]))
    balc = lambda cfg, arm: float(np.mean([cellc(cfg, arm, f, s) for f, s, _ in CELLS]))

    # ---------------------------------------------------------------- per-view evidence on the test sets
    pv = F["per_view_test"]
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{What each view sees on its own, video AUROC. A single view needs no combination, so these "
            "numbers are operator-independent. The last two rows isolate reenactment inside sets that are otherwise "
            "swap-dominated, and are where the temporal and spatial views separate most sharply.}",
            "\\label{tab:perview}", "\\small", "\\begin{tabular}{lrrccc}", "\\toprule",
            "Test set & real & fake & $T$ & $A$ & $O$ \\\\", "\\midrule"]
    for tn in TESTS:
        d = pv.get(tn)
        if d:
            best = max(d["T"], d["APP"], d["OM"])
            c = [("\\textbf{%.4f}" % d[k]) if abs(d[k] - best) < 1e-12 else f"{d[k]:.4f}" for k in ("T", "APP", "OM")]
            body.append(f"{SHORT[tn]} & {d['n_real']} & {d['n_fake']} & " + " & ".join(c) + " \\\\")
    body.append("\\midrule")
    for tn, lab in (("CDFv3 reenactment", "CDF-v3, reenactment only"),
                    ("KoDF first-order motion", "KoDF, first-order motion")):
        d = pv.get(tn)
        if d:
            best = max(d["T"], d["APP"], d["OM"])
            c = [("\\textbf{%.4f}" % d[k]) if abs(d[k] - best) < 1e-12 else f"{d[k]:.4f}" for k in ("T", "APP", "OM")]
            body.append(f"{lab} & {d['n_real']} & {d['n_fake']} & " + " & ".join(c) + " \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_perview", "\n".join(body), "PAPER_EXTRA_FACTS.json")

    # ---------------------------------------------------------------- reenactment slices, fused
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{Reenactment isolated inside two benchmarks that are otherwise dominated by other "
            "manipulations. The fused system tracks the temporal view rather than the spatial majority.}",
            "\\label{tab:slices}", "\\small", "\\begin{tabular}{lccccc}", "\\toprule",
            "Slice & \\textbf{Ours} & $T{+}O$ & $A{+}O$ & $T$ alone & best spatial \\\\", "\\midrule"]
    for tn, lab in (("CDFv3 reenactment", "CDF-v3 reenactment"), ("KoDF first-order motion", "KoDF FOM")):
        if tn in E["tests"][OURS]:
            d = pv.get(tn, {})
            body.append(f"{lab} & \\textbf{{{t(OURS, tn):.4f}}} & {t('T+OM (PCR6+)', tn):.4f} & "
                        f"{t('APP+OM (PCR6+)', tn):.4f} & {t('T only', tn):.4f} & "
                        f"{max(d.get('APP', float('nan')), d.get('OM', float('nan'))):.4f} \\\\")
    body += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    w("tab_slices", "\n".join(body), "EXP_PCR6P_EXPOSED.json + PAPER_EXTRA_FACTS.json")

    # ---------------------------------------------------------------- cross-configuration robustness on DF40
    NAMES = {"42": "warm+gate spatial, V-JEPA seed 42 (deployed)",
             "T1337": "warm+gate spatial, V-JEPA seed 1337",
             "armB42": "SBI arm B spatial seed 42, V-JEPA seed 42",
             "armB1337": "SBI arm B spatial seed 1337, V-JEPA seed 1337"}
    body = ["\\begin{table}[t]", "\\centering",
            "\\caption{DF40 under four detector configurations. The first two share a spatial recipe and differ in "
            "the temporal seed; the last two are a different spatial training recipe, so the four differ in more "
            "than a seed. Family-balanced means.}",
            "\\label{tab:configs}", "\\small", "\\begin{tabular}{lcccc}", "\\toprule",
            "Configuration & \\textbf{Ours} & Dempster-R & Averaging-R & swap / reenact. \\\\", "\\midrule"]
    for c, lab in NAMES.items():
        if c not in EX or OURS not in EX[c]["df40"]:
            continue
