#!/usr/bin/env python3
"""One page of every tested technique, its verdict, and the decisions still open (for discussion, not yet taken).

    OMP_NUM_THREADS=4 python analysis/tbiom/decision_summary.py

Reads the result JSONs, never memory. Anything not yet produced is printed as TODO(run) so the page is honest while
experiments are still running. Regenerate after any new result lands.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

R = Path("tbiom/reports")


def j(name):
    p = R / name
    return json.load(open(p)) if p.exists() else None


def f(x, d=4, sign=True):
    if x is None or (isinstance(x, float) and x != x):
        return "TODO(run)"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def reliability():
    d = j("EXP_RELIABILITY_CONTROLLER.json")
    if not d:
        return None
    CONDS = ["clean", "jpeg40", "rs06"]
    m = lambda a: float(np.mean([np.mean([r["arms"][a][c]["v31"] for c in CONDS]) for r in d]))
    best = max(["segment MLP", "GRU", "Mamba"], key=m)
    return {"const": m("constant DS-R"), "best_name": best, "best": m(best),
            "delta": float(np.mean([r["boot"][best]["avg"][0] for r in d])),
            "ci_pos": sum(r["boot"][best]["avg"][1] > 0 for r in d)}


def temporal():
    d = j("EXP_TEMPORAL_SAMPLING.json")
    if not d:
        return None
    trig = d.get("_mamba_trigger", {})
    cand = {k: v for k, v in d.items() if v and k.startswith("dense × pooling")}
    ref = d.get("sparse × pooling (reference)")
    c = cand.get("dense × pooling")
    return {"trigger": {k: v["delta"] for k, v in trig.items()},
            "ref_confirm": ref and ref["confirm|clean|DS-R"]["v31"], "cand_confirm": c and c["confirm|clean|DS-R"]["v31"]}


def acquisition():
    d = j("EXP_ACQUISITION_PILOT.json")
    if not d:
        return None
    m = lambda p: float(np.mean([r["policies"][p]["auroc"] for r in d if p in r["policies"]]))
    return {"none": m("no acquisition (k=0)"), "learned": m("supervised one-step (k=1)"),
            "oracle": m("oracle (k=1)"), "null": m("oracle on permuted windows (null, k=1)")}


def pair_stats(rows, key, rule="DS-R"):
    """mean delta and the count of splits whose CI excludes zero, for a comparison stored under `key`."""
    out = {}
    for q in ("clean", "processed", "reenactment"):
        v = [r[key][rule][q] if key in r else None for r in rows]
        v = [x for x in v if x]
        if not v:
            return None
        out[q] = (float(np.mean([x[0] for x in v])), sum(x[1] > 0 for x in v), sum(x[2] < 0 for x in v))
    return out


def freqblender():
    d = j("EXP_FREQBLENDER.json")
    if not d:
        return None
    # this report stores the overall delta under "total", as {"mean":..., "ci":[lo, hi]}, and rates separately
    b = [r["boot"]["DS-R"] for r in d]
    g = lambda arm: float(np.mean([r["arms"][arm]["rates"]["DS-R|clean"][0] for r in d]))
    return {"clean": float(np.mean([x["total"]["mean"] for x in b])),
            "reen": float(np.mean([x["reenactment"]["mean"] for x in b])),
            "fpr": g("Spatial-B-Freq") - g("Spatial-B")}


def augext():
    d = j("EXP_AUGMENTATION_EXTENSION.json")
    if not d:
        return None
    b = [r["boot"]["DS-R"] for r in d]
    return {q: (float(np.mean([x[q][0] for x in b])), sum(x[q][1] > 0 for x in b)) for q in ("clean", "processed", "reenactment")}


def precheck():
    d = j("STAGE3_PRECHECK.json")
    if not d:
        return None
    return pair_stats(d, "boot")


def stage3():
    d = j("EXP_COMBINE_CONFIRM.json")
    if not d:
        return None
    out = {}
    for pname in d[0]["pairs"]:
        v = [r["pairs"][pname]["DS-R"] for r in d]
        out[pname] = {q: (float(np.mean([x[q][0] for x in v])), sum(x[q][1] > 0 for x in v), sum(x[q][2] < 0 for x in v))
                      for q in ("clean", "processed", "reenactment")}
        out[pname]["fpr"] = float(np.mean([x["fpr"] for x in v]))
    return out


def main():
    rel, tmp, acq, fb, ae, pc, s3 = reliability(), temporal(), acquisition(), freqblender(), augext(), precheck(), stage3()
    L = ["# What is in the system, what was tested and rejected, and what is still open", "",
         "Generated by `analysis/tbiom/decision_summary.py` from the result files. Every rejection below is a bounded "
         "negative under a criterion fixed before the experiment ran, not a claim that the idea cannot work. **The "
         "decisions in §3 are open: they are recorded here for discussion and have not been taken.**", "",
         "## 1. In the deployed system (each earned its place under a pre-registered test)", "",
         "| component | evidence |", "|---|---|",
         "| V-JEPA 2 LoRA temporal branch (B-augmented) | carries reenactment (0.974 alone on CDFv3 reenactment) and lifts the ten-set mean from 0.8959 to 0.9155 (`FINAL_TABLE.md`) |",
         "| arm-B processing for that branch | cut the development JPEG collapse from 0.087 to 0.050 (`EXP_DFDCP_DIAGNOSIS.md`) |",
         "| DS-R, conflict-aware evidential fusion with reliability discounting | preferred over logistic stacking on 8/8 view combinations; 0.810 vs 0.756 on JPEG development (`EXP7B_FUSION_COMBOS_seed42.md`) |",
         "| fused vacuity as the uncertainty signal | best error ranker for DS-R: 0.781 clean, 0.807 pooled clean tests (`EXP_UNCERTAINTY.md`) |",
         "| three views (T + Appearance + Off-manifold) | T earns its place decisively (+0.057); Appearance is marginal (+0.0012) and reported as such (`EXP_THREEVIEW_ABLATION.md`) |",
         "", "## 2. Tested and not adopted", "",
         "| technique | headline number | verdict |", "|---|---|---|"]
    if rel:
        L.append(f"| Reliability controllers (MLP / GRU / Mamba over segments) | best learned {rel['best_name']} {rel['best']:.4f} vs constant DS-R {rel['const']:.4f}, Δ {f(rel['delta'])}, CI>0 in {rel['ci_pos']}/5 | fails the +0.005 criterion |")
    else:
        L.append("| Reliability controllers | TODO(run) | |")
    if tmp:
        t = ", ".join(f"{k} {f(v)}" for k, v in tmp["trigger"].items())
        L.append(f"| Dense sampling and a temporal head (Stage 2) | candidate confirm {f(tmp['cand_confirm'], sign=False)} vs reference {f(tmp['ref_confirm'], sign=False)}; GRU − pooling {t} | stopped: margin, robustness and reenactment all fail |")
        L.append("| Mamba as a temporal head | trigger never fired (a GRU head must beat pooling by +0.005 first) | not trained |")
    if acq:
        L.append(f"| Acquisition policy / PPO | no acquisition {acq['none']:.4f}; learned selector {acq['learned']:.4f}; oracle {acq['oracle']:.4f}; **null oracle {acq['null']:.4f}** (each averaged over the three aggregation rules) | no-go: the null oracle beats the real one, so the headroom is label selection |")
    if fb:
        L.append(f"| FreqBlender (local reproduction) | clean {f(fb['clean'])}, reenactment {f(fb['reen'])}, false positives {f(fb['fpr'], 3)} | not adopted: false positives exceed the +0.02 limit |")
    L.append("| Joint training of all branches | development DS-R 0.8768 / 0.8804 (two seeds) vs staged 0.8808; leave-one-out for Off-manifold collapses +0.0102 → +0.0003 | not adopted: no gain, and it removes the disagreement DS-R exploits |")
    if ae:
        L.append(f"| Composed processing, arm E vs arm B (Stage 1B) | processed {f(ae['processed'][0])} (CI>0 in {ae['processed'][1]}/5), clean {f(ae['clean'][0])} | **accepted** within the trainable-views family |")
    if pc:
        L.append(f"| …but arm E vs the DEPLOYED spatial views | clean {f(pc['clean'][0])}, processed {f(pc['processed'][0])} (CI>0 in {pc['processed'][1]}/5), reenactment {f(pc['reenactment'][0])} | does not beat what is deployed |")
    L += ["", "## 3. Open decisions — recorded for discussion, not taken", ""]
    if s3:
        L += ["### Stage 3 route 2 (pre-registered): does composition on the deployed recipe earn adoption?", "",
              "| comparison | clean Δ | processed Δ (CI>0) | reenactment Δ | FPR Δ |", "|---|---:|---:|---:|---:|"]
        for pname, v in s3.items():
            L.append(f"| {pname} | {f(v['clean'][0])} | {f(v['processed'][0])} ({v['processed'][1]}/5) | {f(v['reenactment'][0])} | {f(v['fpr'], 3)} |")
        L += ["", "Adoption requires processed ≥ +0.005 significant in ≥ 3/5 splits, clean ≥ −0.005, no significant "
              "reenactment loss, and FPR ≤ +0.02 — applied to the `UE − deployed` row. See `EXP_COMBINE_CONFIRM.md`.", ""]
    else:
        L += ["### Stage 3 route 2 — TODO(run)", ""]
    L += ["### Override A — adopt arm E for processing robustness (route 3)", "",
          "Arm E does not meet the criteria against the deployed views (§2, last row). Adopting it anyway trades clean "
          "and reenactment for processed robustness; three training seeds are measured so the trade is quantified rather "
          "than assumed. Reported as an override wherever used.", "",
          "### Override B — adopt FreqBlender for its in-the-wild gain", "",
          "FreqBlender improves FFIW by +0.0431 on development and +0.0385 on test under DS-R, and FFIW's own false "
          "positives *fall* (0.054 → 0.029). It failed only on pooled false positives (+0.024 against a +0.02 limit — a "
          "near miss). DeepfakeEval2024 gives no support either way (−0.0035 development, +0.0031 test). Adopting it "
          "would override the frozen limit and must be labelled as such (`EXP_FREQBLENDER.md`).", "",
          "### Override C — report T + Off-manifold as the headline system", "",
          "Appearance earns little beside the other two (+0.0012 under DS-R, −0.0050 under logistic, CI excluding zero "
          "in 0/5 splits). The decision of 2026-09-18 keeps three views and reports the ablation honestly; revisiting it "
          "would simplify the system at the cost of the three-view claim (`EXP_THREEVIEW_ABLATION.md`).", "",
          "## 4. How to read the rejections", "",
          "Each came with the control that makes it interpretable: a null oracle that out-performed the real one "
          "(acquisition), quality descriptors that help in-sample and hurt across source groups (reliability), dense "
          "windows that are order-sensitive where our stored stills are not (temporal), and a crop-geometry confound "
          "caught and withdrawn before it could become a result (FreqBlender v1). Those controls are the reportable "
          "content of a negative."]
    (R / "DECISIONS_AND_OPTIONS.md").write_text("\n".join(L) + "\n")
    print("wrote", R / "DECISIONS_AND_OPTIONS.md")


if __name__ == "__main__":
    main()
